// The paths of the deploy scenario. Pure: the bytes of each size are generated by the k6 script, not here.

import type { ArtifactSize } from '../lib/artifacts.ts';
import { thresholdFor } from '../lib/thresholds.ts';

export const DEPLOY_SIZES: readonly ArtifactSize[] = ['1KB', '1MB', '50MB', '200MB'];
/**
 * The p95 limit of the deploy profile. The iterations cycle through every size, so a quarter of the requests carry the
 * largest artifact and the p95 of the run falls among them: only the limit of the largest size can hold.
 */
export const DEPLOY_P95_MS = Math.max(...DEPLOY_SIZES.map((size) => thresholdFor('deploy', size).p95Ms));
/** A successful Maven deploy answers 200 OK, measured against Ingot 1.1.1. */
export const DEPLOY_EXPECTED_STATUSES: readonly number[] = [200];

/**
 * The path of one deploy. The sequence number must be unique within a run, so that concurrent deploys never write the
 * same file and a release repository never refuses a redeploy.
 */
export function deployPath(
  repository: string,
  coordinate: { readonly groupId: string; readonly artifactId: string },
  sequence: number,
): string {
  const version = `1.0.${sequence}`;
  const directory = coordinate.groupId.split('.').join('/');
  return `/${repository}/${directory}/${coordinate.artifactId}/${version}/${coordinate.artifactId}-${version}.jar`;
}
