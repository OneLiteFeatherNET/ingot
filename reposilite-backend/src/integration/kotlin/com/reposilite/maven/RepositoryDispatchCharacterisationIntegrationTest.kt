package com.reposilite.maven

import com.reposilite.ReposiliteObjectMapper
import com.reposilite.RecommendedLocalSpecificationJunitExtension
import com.reposilite.ReposiliteSpecification
import com.reposilite.configuration.shared.SharedConfigurationFacade
import com.reposilite.maven.application.MavenSettings
import com.reposilite.maven.application.MirroredRepositorySettings
import com.reposilite.maven.application.RepositorySettings
import kong.unirest.core.Unirest
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.extension.ExtendWith
import java.io.File

/**
 * Characterisation of the Maven routes across the repository dispatch. Every request below is answered by the server as it
 * is, and the status, headers and body are compared with the fixtures recorded on main. The fixtures are only re-recorded
 * on purpose: when the environment variable INGOT_CHARACTERISATION_RECORD names a directory, the transcripts are written
 * there instead of being compared.
 *
 * Volatile values are normalised before the comparison: the Date and Last-Modified headers and the port of the instance.
 */
@ExtendWith(RecommendedLocalSpecificationJunitExtension::class)
internal class RepositoryDispatchCharacterisationIntegrationTest : ReposiliteSpecification() {

    private companion object {
        const val GAV = "com/example/app/1.0"
        const val JAR = "$GAV/app-1.0.jar"
        const val POM = "$GAV/app-1.0.pom"
        const val TRANSCRIPT_FIXTURE = "/characterisation/repository-dispatch.txt"
        const val OPENAPI_FIXTURE = "/characterisation/openapi-repository-paths.txt"
        const val GENERATED_OPENAPI_DOCUMENT = "build/tmp/kapt3/classes/main/openapi-plugin/openapi-default.json"
    }

    override fun overrideSharedConfiguration(sharedConfigurationFacade: SharedConfigurationFacade) {
        sharedConfigurationFacade.getDomainSettings<MavenSettings>().update { settings ->
            settings.copy(
                repositories = settings.repositories + listOf(
                    RepositorySettings(id = "settings", redeployment = true),
                    RepositorySettings(id = "typed-hosted", type = RepositoryType.HOSTED, redeployment = true),
                    RepositorySettings(
                        id = "typed-proxy",
                        type = RepositoryType.PROXY,
                        proxied = listOf(MirroredRepositorySettings(reference = upstreamReference(UNSTARTED_UPSTREAM_PORT))),
                    ),
                    RepositorySettings(
                        id = "typed-group",
                        type = RepositoryType.GROUP,
                        proxied = listOf(
                            MirroredRepositorySettings(reference = "typed-hosted"),
                            MirroredRepositorySettings(reference = "releases"),
                        ),
                    ),
                )
            )
        }
    }

    @Test
    fun `responses of the maven routes stay byte for byte the same`() {
        // given: artifacts in the hosted, private and settings repositories
        useDocument("releases", GAV, "app-1.0.jar", "jar-content", store = true)
        useDocument("releases", GAV, "app-1.0.pom", "pom-content", store = true)
        useDocument("settings", GAV, "app-1.0.pom", "settings-pom", store = true)
        useDocument("typed-hosted", GAV, "app-1.0.jar", "typed-jar", store = true)
        useDocument("private", GAV, "app-1.0.jar", "private-jar", store = true)

        // when: every probe is sent and the exchanges are rendered
        val (name, secret) = useDefaultManagementToken()
        val transcript = renderTranscript(base, name, secret, probes())

        // then: the transcript equals the fixture recorded on main
        compareWithFixture(TRANSCRIPT_FIXTURE, transcript)
    }

    /**
     * The document is generated by the annotation processor at compile time into the kapt output. The runtime
     * /openapi answers an empty document under the test classpath, so the generated file is the one that is compared.
     */
    @Test
    fun `the openapi document lists the same repository paths as on main`() {
        // given: the document generated from the @OpenApi annotations of this build
        val document = File(GENERATED_OPENAPI_DOCUMENT)
        assertThat(document.isFile)
            .describedAs("the generated openapi document must exist at ${document.absolutePath}")
            .isTrue

        // when: the operations of the repository paths are listed with their methods and tags
        val paths = ReposiliteObjectMapper.DEFAULT_OBJECT_MAPPER.readTree(document)
            .path("paths")
            .fields()
            .asSequence()
            .filter { (path, _) -> path.startsWith("/{repository}") }
            .flatMap { (path, item) ->
                item.fields().asSequence().map { (method, operation) ->
                    "$path ${method.uppercase()} ${operation.path("tags").joinToString(",") { it.asText() }}"
                }
            }
            .sorted()
            .joinToString("\n", postfix = "\n")

        // then: they equal the fixture recorded on main
        compareWithFixture(OPENAPI_FIXTURE, paths)
    }

    private fun probes(): List<CharacterisationProbe> = listOf(
        CharacterisationProbe("hosted file, anonymous read", "GET", "releases/$JAR"),
        CharacterisationProbe("hosted file, head", "HEAD", "releases/$JAR"),
        CharacterisationProbe("hosted pom, gradle accept", "GET", "releases/$POM", headers = mapOf("Accept" to "*/*")),
        CharacterisationProbe("settings repository, gradle request", "GET", "settings/$POM", headers = mapOf("Accept" to "*/*")),
        // The dashboard page: its bundles and their sizes change with every frontend release, so only its anchor is recorded.
        CharacterisationProbe("settings repository, browser navigation", "GET", "settings", headers = navigation(), anchor = "<div id=\"app\">"),
        CharacterisationProbe("directory index", "GET", "releases/$GAV/"),
        CharacterisationProbe("missing file", "GET", "releases/$GAV/missing.jar"),
        CharacterisationProbe("unknown repository, read", "GET", "missing/$JAR"),
        CharacterisationProbe("api path without route", "GET", "api/unknown"),
        CharacterisationProbe("private repository, anonymous", "GET", "private/$JAR"),
        CharacterisationProbe("private repository, authenticated", "GET", "private/$JAR", auth = true),
        CharacterisationProbe("proxy, unavailable upstream", "GET", "proxied/$JAR"),
        CharacterisationProbe("proxy, head", "HEAD", "proxied/$JAR"),
        CharacterisationProbe("hosted, put anonymous", "PUT", "releases/$GAV/new.jar", body = "new"),
        CharacterisationProbe("hosted, put authenticated", "PUT", "releases/$GAV/new.jar", body = "new", auth = true),
        CharacterisationProbe("hosted, post authenticated", "POST", "releases/$GAV/posted.jar", body = "posted", auth = true),
        CharacterisationProbe("hosted, delete anonymous", "DELETE", "releases/$JAR"),
        CharacterisationProbe("hosted, delete authenticated", "DELETE", "releases/$GAV/new.jar", auth = true),
        CharacterisationProbe("typed hosted, put authenticated", "PUT", "typed-hosted/$GAV/new.jar", body = "typed", auth = true),
        CharacterisationProbe("typed proxy, put authenticated", "PUT", "typed-proxy/$JAR", body = "refused", auth = true),
        CharacterisationProbe("typed proxy, delete authenticated", "DELETE", "typed-proxy/$JAR", auth = true),
        CharacterisationProbe("typed group, read", "GET", "typed-group/$JAR"),
        CharacterisationProbe("typed group, read missing", "GET", "typed-group/$GAV/missing.jar"),
        CharacterisationProbe("typed group, put authenticated", "PUT", "typed-group/$GAV/new.jar", body = "group", auth = true),
        CharacterisationProbe("unknown repository, put authenticated", "PUT", "missing/$JAR", body = "missing", auth = true),
        CharacterisationProbe("unknown repository, delete authenticated", "DELETE", "missing/$JAR", auth = true),
    )

    private fun navigation() = mapOf(
        "Accept" to "text/html,application/xhtml+xml",
        "Sec-Fetch-Mode" to "navigate",
        "Sec-Fetch-Dest" to "document",
        "Sec-Fetch-Site" to "none",
    )

}
