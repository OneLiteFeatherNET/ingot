@file:Suppress("FunctionName")

package com.reposilite.plugin

import com.reposilite.ReposiliteParameters
import com.reposilite.ReposiliteSpecification
import com.reposilite.RecommendedLocalSpecificationJunitExtension
import com.reposilite.token.ExportService
import com.reposilite.token.Route
import com.reposilite.token.RoutePermission.WRITE
import kong.unirest.core.Unirest
import org.apache.commons.codec.digest.DigestUtils
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.extension.ExtendWith
import panda.std.ResultAssertions.assertOk
import java.io.File
import java.nio.file.Files

/**
 * Loads the jars that upstream published for the bundled plugins, unchanged, into a fresh Ingot instance. A plugin written
 * against Reposilite 3.5.28 links against the same classes, so these tests fail when Ingot removes or changes something
 * the plugins call, even though every Ingot test still passes. The jars come from Gradle (the `pluginCanary` configuration
 * of reposilite-backend), never from the network of the test.
 */
@ExtendWith(RecommendedLocalSpecificationJunitExtension::class)
internal class UpstreamPluginCanaryIntegrationTest : ReposiliteSpecification() {

    override fun overrideParameters(parameters: ReposiliteParameters) {
        // given: the upstream plugin jars in the plugins directory, and the legacy tokens.dat of the migration fixture
        val pluginsDirectory = Files.createDirectories(parameters.pluginDirectory)
        upstreamPluginJars().forEach { jar -> Files.copy(jar.toPath(), pluginsDirectory.resolve(jar.name)) }

        val fixture = checkNotNull(javaClass.getResourceAsStream(TOKENS_FIXTURE)) { "Missing test resource $TOKENS_FIXTURE" }
        fixture.use { Files.copy(it, parameters.workingDirectory.resolve("tokens.dat")) }
    }

    @Test
    fun `should answer the sha256 checksum of a deployed artifact through the upstream checksum plugin`() {
        // given: an artifact deployed to a repository without mirrors and without a checksum file
        val content = "upstream-canary-artifact"
        useDocument("releases", "com/reposilite/canary", "canary-1.0.jar", content, store = true)

        // when: the sha256 checksum of the artifact is requested
        val response = Unirest.get("$base/releases/com/reposilite/canary/canary-1.0.jar.sha256").asString()

        // then: the upstream checksum plugin has generated and served the digest of the artifact
        assertThat(response.status)
            .describedAs("status of the sha256 request, expected 200 from the upstream checksum plugin")
            .isEqualTo(200)
        assertThat(response.body.trim())
            .describedAs("sha256 served for canary-1.0.jar, expected the digest generated by the upstream checksum plugin")
            .isEqualTo(DigestUtils.sha256Hex(content))
    }

    @Test
    fun `should export the token of a legacy tokens dat file through the upstream migration plugin`() {
        // given: a legacy tokens.dat in the working directory, written before the instance started (see overrideParameters)
        val exported = reposiliteWorkingDirectory.toPath().resolve("tokens.json")

        // when: the instance has started, so the upstream migration plugin has run during its initialisation
        // then: the plugin has exported the token of the fixture with its route
        assertThat(exported)
            .describedAs("tokens.json written by the upstream migration plugin, the plugin did not run or did not export")
            .exists()

        val tokens = assertOk(ExportService().importFromFile(exported))
        assertThat(tokens.map { it.accessToken.name })
            .describedAs("token names exported from tokens.dat")
            .contains("private")

        val privateToken = tokens.first { it.accessToken.name == "private" }
        assertThat(privateToken.routes)
            .describedAs("routes of token 'private' exported from tokens.dat")
            .contains(Route("/private", WRITE))
    }

    private fun upstreamPluginJars(): List<File> =
        checkNotNull(System.getProperty(PLUGIN_JARS_PROPERTY)) {
            "$PLUGIN_JARS_PROPERTY is not set, run the suite through :reposilite-backend:integration"
        }
            .split(File.pathSeparator)
            .filter { it.isNotBlank() }
            .map(::File)

    private companion object {
        const val PLUGIN_JARS_PROPERTY = "reposilite.canary.plugins"
        const val TOKENS_FIXTURE = "/plugin-canary/tokens.dat"
    }

}
